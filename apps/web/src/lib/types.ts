import type { AdLinkRel } from "@devfeed/ui/ad-link-rel";

export type Source = {
  id: string;
  slug: string;
  name: string;
  provider?: "rss" | "youtube";
  resource_kind?: "feed" | "channel" | "playlist" | "video";
  provider_resource_id?: string | null;
  recurring?: boolean;
  website_url: string | null;
  logo_url: string | null;
  logo_variants?: { url: string; width: number }[];
  image_url?: string | null;
  description: string | null;
};
export type Topic = {
  id: string;
  name: string;
  slug: string;
  kind: string;
  description: string | null;
  ai_description: string | null;
  logo_url: string | null;
  logo_variants?: { url: string; width: number }[];
  website_url: string | null;
};
export type VideoMetadata = {
  channel_id?: string | null;
  channel_title?: string | null;
  channel_url?: string | null;
  duration_seconds?: number | null;
  availability?: "public" | "unavailable";
  retrieved_at?: string | null;
};
export type Article = {
  provider?: "youtube" | null;
  provider_resource_id?: string | null;
  video_metadata?: VideoMetadata | null;
  id: string;
  slug: string;
  canonical_url: string;
  title: string;
  summary: string;
  ai_summary: string | null;
  ai_description: string | null;
  image_url: string | null;
  image_variants?: { url: string; width: number }[];
  author: string | null;
  content_type: string;
  content_format: string | null;
  language: string | null;
  published_at: string | null;
  feed_at: string;
  tags: string[];
  sources: Source[];
  topics: (Pick<Topic, "id" | "name" | "slug" | "kind"> & { role?: string })[];
  sponsor_names?: string[];
  sponsor_link_rel?: AdLinkRel[];
};
export type FeedPage = { items: Article[]; next_cursor: string | null };
export type FeedOptions = { content_types: string[]; sources: Source[] };
