import { pathToFileURL } from "node:url";
import { createRouteGenerator } from "./lib/concrete-routes.mjs";

const generator = createRouteGenerator({
  namespace: "user",
  name: "reader",
  label: "Reader",
  generateCommand: "web:generate",
  marker: " * Generated by scripts/generate_reader_routes.mjs. Do not edit.",
  operationType: "ReaderGatewayOperation",
  operationExport: "userGatewayOperations",
  operationsImport: "@/lib/api/generated/user-operations",
  bindings: {
    forward: { name: "bindReaderOperation", module: "@/lib/server/gateway" },
    "placement-query": {
      name: "bindPersonalizedPartnerPlacements",
      module: "@/lib/server/partner-placements",
    },
  },
  reject: { name: "rejectReaderMethod", module: "@/lib/server/gateway" },
  source: new URL("../apps/web/openapi.json", import.meta.url),
  target: new URL("../apps/web/src/lib/api/generated/user-operations.ts", import.meta.url),
  routesRoot: new URL("../apps/web/src/app/api/v1/user", import.meta.url),
});

export const readerRoutePlan = generator.plan;
export const renderReaderRoutes = generator.render;
export const generateReaderRoutes = generator.generate;

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const arguments_ = process.argv.slice(2);
  if (arguments_.length > 1 || (arguments_.length === 1 && arguments_[0] !== "--check")) {
    throw new Error("Usage: node scripts/generate_reader_routes.mjs [--check]");
  }
  await generateReaderRoutes({ check: arguments_.includes("--check") });
  console.log(`Reader concrete API routes ${arguments_.length ? "checked" : "generated"}`);
}
