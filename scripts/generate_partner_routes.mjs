import { pathToFileURL } from "node:url";
import { createRouteGenerator } from "./lib/concrete-routes.mjs";

const generator = createRouteGenerator({
  namespace: "partner",
  name: "partner",
  label: "Partner",
  marker: " * Generated by scripts/generate_partner_routes.mjs. Do not edit.",
  operationType: "GatewayOperation",
  operationExport: "partnerGatewayOperations",
  operationsImport: "@/lib/api/generated/partner-operations",
  bindings: { forward: { name: "bindPartnerOperation", module: "@/lib/server/gateway" } },
  reject: { name: "rejectPartnerMethod", module: "@/lib/server/gateway" },
  source: new URL("../apps/partner/openapi.json", import.meta.url),
  target: new URL("../apps/partner/src/lib/api/generated/partner-operations.ts", import.meta.url),
  routesRoot: new URL("../apps/partner/src/app/api/v1/partner", import.meta.url),
});

export const partnerRoutePlan = generator.plan;
export const renderPartnerRoutes = generator.render;
export const generatePartnerRoutes = generator.generate;

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const arguments_ = process.argv.slice(2);
  if (arguments_.length > 1 || (arguments_.length === 1 && arguments_[0] !== "--check")) {
    throw new Error("Usage: node scripts/generate_partner_routes.mjs [--check]");
  }
  await generatePartnerRoutes({ check: arguments_.includes("--check") });
  console.log(`Partner concrete API routes ${arguments_.length ? "checked" : "generated"}`);
}
