import { lstat, mkdir, readFile, realpath, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format } from "prettier";
import ts from "typescript";
import {
  extensionTransportPolicy,
  gatewayOperations,
  gatewayParameterSchema,
  gatewayPolicy,
  releaseVersion,
} from "./lib/gateway-contract.mjs";

const marker = " * Generated by scripts/generate_extension_operations.mjs. Do not edit.";
const methods = new Set(["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"]);
const defaults = {
  source: new URL("../apps/web/openapi.json", import.meta.url),
  bindings: new URL("../apps/web/src/lib/api/reader-bindings.json", import.meta.url),
  apiRoot: new URL("../apps/web/src/app/api", import.meta.url),
  target: new URL("../apps/web/src/lib/api/generated/extension-operations.ts", import.meta.url),
};

function object(value, label, accepted) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${label} must be an object`);
  }
  if (accepted) {
    for (const key of Object.keys(value)) {
      if (!accepted.includes(key)) throw new Error(`${label} has unsupported field ${key}`);
    }
  }
  return value;
}

function identity(value, label) {
  if (typeof value !== "string" || !/^[A-Za-z_][A-Za-z0-9_]*$/u.test(value)) {
    throw new Error(`${label} needs a safe operationId`);
  }
  return value;
}

function routeTemplate(routeFile) {
  if (
    typeof routeFile !== "string" ||
    !/\/route\.tsx?$/u.test(routeFile) ||
    /[\\%?#\s\x00-\x1f\x7f]/u.test(routeFile)
  ) {
    throw new Error("Public binding needs a relative Next route.ts file");
  }
  const filenames = routeFile.split("/").slice(0, -1);
  const parameters = [];
  const parts = filenames.map((part, index) => {
    const dynamic = /^\[(\.\.\.)?([A-Za-z_][A-Za-z0-9_]*)\]$/u.exec(part);
    if (dynamic) {
      const [, catchAll, name] = dynamic;
      if (parameters.some((item) => item.name === name)) {
        throw new Error(`Public route ${routeFile} repeats a parameter`);
      }
      if (catchAll && index !== filenames.length - 1) {
        throw new Error(`Public route ${routeFile} needs a terminal catch-all`);
      }
      parameters.push({ name, converter: catchAll ? "path" : "str" });
      return `{${name}}`;
    }
    if (!/^[A-Za-z0-9_.:-]+$/u.test(part) || part === "." || part === "..") {
      throw new Error(`Public route ${routeFile} has an unsupported Next segment`);
    }
    return part;
  });
  return { path: `/api/${parts.join("/")}`, parameters, filenames };
}

function httpExports(content, filename) {
  const source = ts.createSourceFile(filename, content, ts.ScriptTarget.Latest, true);
  if (source.parseDiagnostics.length) throw new Error(`Cannot parse Next route ${filename}`);
  const exports = new Set();
  for (const statement of source.statements) {
    if (ts.isExportDeclaration(statement) && !statement.isTypeOnly) {
      if (statement.exportClause && ts.isNamedExports(statement.exportClause)) {
        for (const element of statement.exportClause.elements) {
          if (!element.isTypeOnly && methods.has(element.name.text)) exports.add(element.name.text);
        }
      }
    } else if (
      statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword) &&
      !statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.DefaultKeyword)
    ) {
      if (ts.isFunctionDeclaration(statement) && statement.name && statement.body) {
        if (methods.has(statement.name.text)) exports.add(statement.name.text);
      } else if (ts.isVariableStatement(statement)) {
        for (const declaration of statement.declarationList.declarations) {
          if (
            ts.isIdentifier(declaration.name) &&
            declaration.initializer &&
            methods.has(declaration.name.text)
          ) {
            exports.add(declaration.name.text);
          }
        }
      }
    }
  }
  return exports;
}

async function routeSource(root, routeFile) {
  const destination = resolve(root, routeFile);
  const inside = relative(root, destination);
  if (!inside || isAbsolute(inside) || inside.startsWith(`..${sep}`)) {
    throw new Error(`Public route ${routeFile} escapes the API directory`);
  }
  let current = root;
  for (const part of routeFile.split("/")) {
    current = resolve(current, part);
    const stat = await lstat(current);
    if (stat.isSymbolicLink()) throw new Error(`Public route ${routeFile} is symlinked`);
  }
  if (!(await lstat(destination)).isFile())
    throw new Error(`Public route ${routeFile} is not a file`);
  return readFile(destination, "utf8");
}

function validateNextNames(routes) {
  const tree = { children: new Map() };
  for (const filenames of routes) {
    let node = tree;
    for (const filename of filenames) {
      const key = filename.startsWith("[") ? "dynamic" : filename;
      let child = node.children.get(key);
      if (!child) {
        child = { filename, children: new Map() };
        node.children.set(key, child);
      } else if (child.filename !== filename) {
        throw new Error(`Conflicting public Next route names ${child.filename} and ${filename}`);
      }
      node = child;
    }
  }
}

/** Compile public BFF declarations against actual route exports and backend identities. */
export async function extensionOperationPlan(
  document,
  declaration,
  { apiRoot = defaults.apiRoot } = {},
) {
  const user = gatewayOperations(document, { namespace: "user" });
  const catalog = document["x-devfeed-public-operations"];
  if (!Array.isArray(catalog) || !catalog.length)
    throw new Error("Missing public backend operation catalog");
  const backend = new Map();
  for (const operation of [...user, ...catalog]) {
    if (catalog.includes(operation))
      object(operation, "Public backend operation", ["operationId", "method", "path"]);
    identity(operation.operationId, "Backend operation");
    if (backend.has(operation.operationId))
      throw new Error(`Duplicate backend identity ${operation.operationId}`);
    if (!methods.has(operation.method))
      throw new Error("Backend catalog uses an unsupported method");
    if (
      typeof operation.path !== "string" ||
      !operation.path.startsWith("/") ||
      /[\\%?#\s\x00-\x1f\x7f]/u.test(operation.path)
    ) {
      throw new Error("Backend catalog uses an unsafe path");
    }
    backend.set(operation.operationId, operation);
  }
  object(declaration, "Reader bindings", ["bindings"]);
  if (!Array.isArray(declaration.bindings))
    throw new Error("Reader bindings must declare an array");
  const ids = new Set(backend.keys());
  const signatures = new Set();
  const root = await realpath(apiRoot instanceof URL ? fileURLToPath(apiRoot) : apiRoot);
  const routes = [];
  const publicOperations = [];
  for (const binding of declaration.bindings) {
    object(binding, "Reader binding", [
      "operationId",
      "routeFile",
      "method",
      "parameters",
      "backendOperations",
      "policy",
    ]);
    identity(binding.operationId, "Reader binding");
    if (ids.has(binding.operationId))
      throw new Error(`Duplicate reader identity ${binding.operationId}`);
    ids.add(binding.operationId);
    if (!methods.has(binding.method))
      throw new Error(`Unsupported reader method ${binding.method}`);
    const template = routeTemplate(binding.routeFile);
    const content = await routeSource(root, binding.routeFile);
    if (!httpExports(content, binding.routeFile).has(binding.method)) {
      throw new Error(`Next route ${binding.routeFile} does not export ${binding.method}`);
    }
    if (
      !Array.isArray(binding.parameters) ||
      binding.parameters.length !== template.parameters.length
    ) {
      throw new Error(`Reader binding ${binding.operationId} has incomplete parameters`);
    }
    const parameters = new Map();
    for (const parameter of binding.parameters) {
      object(parameter, "Reader parameter", ["name", "converter", "schema"]);
      const expected = template.parameters.find(({ name }) => name === parameter.name);
      if (!expected || parameters.has(parameter.name))
        throw new Error("Reader binding has an unknown or repeated parameter");
      if (
        (expected.converter === "path" && parameter.converter !== "path") ||
        (expected.converter === "str" && !["str", "uuid"].includes(parameter.converter))
      ) {
        throw new Error("Reader parameter converter does not match its Next route");
      }
      const schema = gatewayParameterSchema(
        document,
        parameter.schema,
        `Reader parameter ${parameter.name}`,
      );
      if (parameter.converter === "uuid" && schema.format !== "uuid")
        throw new Error("Reader UUID converter needs a UUID schema");
      parameters.set(parameter.name, {
        name: parameter.name,
        converter: parameter.converter,
        schema,
      });
    }
    if (
      !Array.isArray(binding.backendOperations) ||
      new Set(binding.backendOperations).size !== binding.backendOperations.length
    ) {
      throw new Error("Reader binding needs distinct backend operation references");
    }
    for (const reference of binding.backendOperations) {
      if (!backend.has(reference)) throw new Error(`Unknown backend operation ${reference}`);
    }
    const declared = object(binding.policy, "Reader binding policy", [
      "bodyLimit",
      "bodyTimeoutMs",
      "upstreamTimeoutMs",
      "extension",
    ]);
    const { extension, ...bounds } = declared;
    const policy = {
      ...gatewayPolicy(bounds, "Reader binding policy", "public"),
      extension: extensionTransportPolicy(extension, "Reader binding extension policy"),
    };
    const signature = `${binding.method} ${template.path.replace(/\{[^}]+\}/gu, "{}")}`;
    if (signatures.has(signature)) throw new Error(`Duplicate public reader route ${signature}`);
    signatures.add(signature);
    routes.push(template.filenames);
    publicOperations.push({
      operationId: binding.operationId,
      method: binding.method,
      path: template.path,
      parameters: template.parameters.map(({ name }) => parameters.get(name)),
      policy,
    });
  }
  validateNextNames(routes);
  const privateOperations = user
    .filter(({ policy }) => policy.extension !== null)
    .map((operation) => ({ ...operation, path: `/api${operation.path}` }));
  for (const operation of privateOperations) {
    const signature = `${operation.method} ${operation.path.replace(/\{[^}]+\}/gu, "{}")}`;
    if (signatures.has(signature))
      throw new Error(`Conflicting private/public reader route ${signature}`);
    signatures.add(signature);
  }
  return { privateOperations, publicOperations };
}

export async function renderExtensionOperations(document, declaration, options) {
  const version = releaseVersion(document);
  const { privateOperations, publicOperations } = await extensionOperationPlan(
    document,
    declaration,
    options,
  );
  const entries = [
    ...privateOperations.map(
      ({ operationId, path }) =>
        `{...userGatewayOperations[${JSON.stringify(operationId)}],path:${JSON.stringify(path)}}`,
    ),
    ...publicOperations.map((operation) => JSON.stringify(operation)),
  ];
  return format(
    `/**\n${marker}\n * OpenAPI spec version: ${version}\n */\n` +
      `import type { ExtensionGatewayOperation } from "@devfeed/http/gateway";\n` +
      `import { userGatewayOperations } from "./user-operations";\n\n` +
      `export const extensionGatewayOperations = [\n${entries.join(",\n")}\n] as const satisfies readonly ExtensionGatewayOperation[];\n`,
    { parser: "typescript", printWidth: 100 },
  );
}

export async function generateExtensionOperations({
  source = defaults.source,
  bindings = defaults.bindings,
  apiRoot = defaults.apiRoot,
  target = defaults.target,
  check = false,
} = {}) {
  const [document, declaration] = await Promise.all([
    readFile(source, "utf8"),
    readFile(bindings, "utf8"),
  ]);
  const generated = await renderExtensionOperations(JSON.parse(document), JSON.parse(declaration), {
    apiRoot,
  });
  let previous;
  try {
    if (!(await lstat(target)).isFile())
      throw new Error("Cannot manage a non-file extension operation definition");
    previous = await readFile(target, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (previous !== undefined && !previous.includes(marker))
    throw new Error("Refusing to overwrite a handwritten extension operation definition");
  if (check) {
    if (previous !== generated)
      throw new Error("Extension operations are stale; run npm run web:generate");
    return;
  }
  const destination = target instanceof URL ? fileURLToPath(target) : target;
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, generated);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const arguments_ = process.argv.slice(2);
  if (arguments_.length > 1 || (arguments_.length === 1 && arguments_[0] !== "--check")) {
    throw new Error("Usage: node scripts/generate_extension_operations.mjs [--check]");
  }
  await generateExtensionOperations({ check: arguments_.includes("--check") });
  console.log(`Extension operation registry ${arguments_.length ? "checked" : "generated"}`);
}
